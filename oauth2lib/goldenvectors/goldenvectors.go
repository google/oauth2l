// Package goldenvectors holds test vectors for oauth2lib: for a given input,
// the HTTP requests oauth2lib must send, the responses to give it, and the
// token or error it must return.
//
// The vectors are embedded with //go:embed, so other modules' tests (such as
// Go gcloud's) can read them without Blaze runfiles or file paths. oauth2lib
// runs every vector in its own tests, and the request bodies are checked
// against Python gcloud and google-auth. See README.md for the format.
//
// The package imports only the standard library.
package goldenvectors

import (
	"embed"
	"encoding/json"
	"fmt"
	"io/fs"
	"path"
	"sort"
	"strings"
)

// FS holds the vector files, one JSON-encoded Vector per file.
//
//go:embed *.json
var FS embed.FS

// PrivateKeyPlaceholder stands for a service account private key in
// Config.CredentialsJSON, so that no key is checked in. Config.JSON replaces
// it with a PEM-encoded RSA key generated by the test.
const PrivateKeyPlaceholder = "TEST_PRIVATE_KEY_PEM"

// Sentinel error names used in Error.Is.
const (
	ErrReauthRequired = "ErrReauthRequired"
	ErrAccessDenied   = "ErrAccessDenied"
	ErrCAADenied      = "ErrCAADenied"
	ErrInvalidGrant   = "ErrInvalidGrant"
	ErrTransient      = "ErrTransient"
)

// Vector is one test case.
type Vector struct {
	// Name is the file name without ".json".
	Name        string `json:"name"`
	Description string `json:"description"`
	// Python names the Python gcloud or google-auth code that sends the
	// same requests, for reviewers.
	Python    string     `json:"python,omitempty"`
	Input     Input      `json:"input"`
	Exchanges []Exchange `json:"exchanges"`
	Expected  Expected   `json:"expected"`
}

// Input is how the credentials are built. Exactly one of Config and
// Impersonation is set.
type Input struct {
	// Config is passed to oauth2lib.BuildCredentials.
	Config *Config `json:"config,omitempty"`
	// Impersonation is passed to oauth2lib.Impersonate.
	Impersonation *Impersonation `json:"impersonation,omitempty"`
}

// Config mirrors oauth2lib.Config. The test supplies Client and Logger.
type Config struct {
	// CredentialsJSON is the credential file. A "private_key" may be
	// PrivateKeyPlaceholder; use JSON to get the bytes to pass.
	CredentialsJSON  json.RawMessage `json:"credentials_json"`
	Scopes           []string        `json:"scopes,omitempty"`
	TokenURL         string          `json:"token_url,omitempty"`
	UniverseDomain   string          `json:"universe_domain,omitempty"`
	UseSelfSignedJWT bool            `json:"use_self_signed_jwt,omitempty"`
	// RAPT, if set, is what Config.RAPT returns.
	RAPT string `json:"rapt,omitempty"`
}

// JSON returns CredentialsJSON with every PrivateKeyPlaceholder string
// replaced by privateKeyPEM.
func (c Config) JSON(privateKeyPEM string) ([]byte, error) {
	quoted, err := json.Marshal(privateKeyPEM)
	if err != nil {
		return nil, err
	}
	return []byte(strings.ReplaceAll(string(c.CredentialsJSON), `"`+PrivateKeyPlaceholder+`"`, string(quoted))), nil
}

// Impersonation mirrors oauth2lib.ImpersonationConfig. Source is built with
// BuildCredentials; the test supplies Client and Logger to both.
type Impersonation struct {
	Source          Config   `json:"source"`
	Target          string   `json:"target"`
	Delegates       []string `json:"delegates,omitempty"`
	Scopes          []string `json:"scopes"`
	LifetimeSeconds int      `json:"lifetime_seconds,omitempty"`
	Endpoint        string   `json:"endpoint,omitempty"`
}

// Exchange is one HTTP request oauth2lib must send, in order, and the
// response to give it.
type Exchange struct {
	Request  Request  `json:"request"`
	Response Response `json:"response"`
}

// Request is what the request must look like.
type Request struct {
	Method string `json:"method"`
	// URL is the full URL, including the query, if any.
	URL string `json:"url"`
	// Headers must be present with exactly these values. Other headers
	// are allowed.
	Headers map[string]string `json:"headers,omitempty"`
	// Form is the exact set of form fields of a form-encoded body, except
	// "assertion" when Assertion is set.
	Form map[string]string `json:"form,omitempty"`
	// Assertion describes the JWT in the form's "assertion" field.
	Assertion *JWT `json:"assertion,omitempty"`
	// JSON is the body of a JSON request, compared as JSON values.
	JSON json.RawMessage `json:"json,omitempty"`
}

// JWT describes a JWT signed with the test's private key. Time-dependent
// claims (iat and exp) are checked with LifetimeSeconds.
type JWT struct {
	// Header and Claims list fields the JWT must have, with these values.
	// Other fields are allowed.
	Header map[string]any `json:"header,omitempty"`
	Claims map[string]any `json:"claims"`
	// AbsentClaims must not be in the JWT.
	AbsentClaims []string `json:"absent_claims,omitempty"`
	// LifetimeSeconds is exp minus iat.
	LifetimeSeconds int64 `json:"lifetime_seconds"`
}

// Response is the response to give. If TransportError is set, the client
// gets that error instead of a response.
type Response struct {
	// Status is the HTTP status code; 0 means 200.
	Status int `json:"status,omitempty"`
	// Body is sent as JSON with Content-Type application/json.
	Body json.RawMessage `json:"body,omitempty"`
	// BodyText, if set instead of Body, is sent as text/plain.
	BodyText       string `json:"body_text,omitempty"`
	TransportError string `json:"transport_error,omitempty"`
}

// Expected is the outcome of Token. Exactly one of Token and Error is set.
type Expected struct {
	Token *Token `json:"token,omitempty"`
	Error *Error `json:"error,omitempty"`
	// UniverseDomain is what the credentials' UniverseDomain returns.
	UniverseDomain string `json:"universe_domain"`
}

// Token is the expected *auth.Token.
type Token struct {
	// Value is the token, unless JWT is set.
	Value string `json:"value,omitempty"`
	// JWT, if set, describes the token, which is a self-signed JWT.
	JWT  *JWT   `json:"jwt,omitempty"`
	Type string `json:"type"`
	// ExpiresInSeconds is Expiry minus the time of the call, if set.
	ExpiresInSeconds *int64 `json:"expires_in_seconds,omitempty"`
	// Expiry is the exact Expiry (RFC 3339), if set. If neither is set,
	// Expiry is zero.
	Expiry string `json:"expiry,omitempty"`
	// Metadata is the token's exact Metadata (oauth2lib.Metadata* keys).
	Metadata map[string]string `json:"metadata"`
}

// Error is the expected *oauth2lib.RefreshError.
type Error struct {
	// Kind is the ErrorKind's String, such as "reauth required".
	Kind        string `json:"kind"`
	Code        string `json:"code,omitempty"`
	Subtype     string `json:"subtype,omitempty"`
	Description string `json:"description,omitempty"`
	StatusCode  int    `json:"status_code,omitempty"`
	// Is lists the sentinel errors (ErrReauthRequired, ...) the error
	// matches with errors.Is. It must not match the others.
	Is []string `json:"is,omitempty"`
}

// All returns every vector, sorted by name. It fails if a file doesn't
// parse, has unknown fields, or its name doesn't match the file name.
func All() ([]Vector, error) {
	names, err := fs.Glob(FS, "*.json")
	if err != nil {
		return nil, err
	}
	sort.Strings(names)
	vectors := make([]Vector, 0, len(names))
	for _, name := range names {
		b, err := FS.ReadFile(name)
		if err != nil {
			return nil, err
		}
		dec := json.NewDecoder(strings.NewReader(string(b)))
		dec.DisallowUnknownFields()
		var v Vector
		if err := dec.Decode(&v); err != nil {
			return nil, fmt.Errorf("goldenvectors: %s: %w", name, err)
		}
		if want := strings.TrimSuffix(path.Base(name), ".json"); v.Name != want {
			return nil, fmt.Errorf("goldenvectors: %s: name is %q, want %q", name, v.Name, want)
		}
		vectors = append(vectors, v)
	}
	return vectors, nil
}
